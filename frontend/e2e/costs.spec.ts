import { expect, test } from '@playwright/test';
import { resolve } from 'node:path';

test('guest offline mock, filtering and feed', async ({ page }) => {
  await page.route(/\/api\/costs(?:[/?]|$)/, route => route.abort('connectionrefused'));
  await page.goto('/costs');
  await expect(page.getByText('Найдено: 6')).toBeVisible();
  await page.screenshot({ path: 'test-results/mock-catalog.png' });
  await page.getByLabel('Код издержки от').fill('25');
  await page.getByLabel('Код издержки до').fill('26');
  await page.getByRole('button', { name: 'Применить', exact: true }).click();
  await expect(page.getByText('Найдено: 2')).toBeVisible();
  await page.getByRole('link', { name: /Аренда кофемашины/ }).click();
  await expect(page.getByRole('heading', { name: 'Аренда кофемашины' })).toBeVisible();
  await page.screenshot({ path: 'test-results/mock-feed.png' });
  await expect(page.getByRole('button', { name: 'Поставить лайк' })).toBeDisabled();
  await page.getByRole('button', { name: 'Следующая издержка' }).click();
  await expect(page.getByRole('heading', { name: 'Подписка для кассы' })).toBeVisible();
  await page.getByRole('button', { name: 'Плитка', exact: true }).click();
  await expect(page.getByLabel('Код издержки от')).toHaveValue('25');
});

test('cookie login, multipart draft, publish, like, F5 guest, logout, soft delete', async ({ page }) => {
  const name = `lab6_${Date.now()}`;
  const password = 'CostLab6_test_2026';
  await page.goto('/costs');
  await expect(page.getByText('Найдено:', { exact: false })).toBeVisible();
  await page.getByRole('button', { name: 'Вход', exact: true }).click();
  await page.getByRole('button', { name: 'Создать учётную запись' }).click();
  await page.getByLabel('Имя пользователя', { exact: true }).fill(name);
  await page.getByLabel('Пароль', { exact: true }).fill(password);
  await page.getByRole('button', { name: 'Зарегистрироваться', exact: true }).click();
  await expect(page.getByText('Регистрация выполнена.', { exact: false })).toBeVisible();
  await page.getByRole('button', { name: 'Войти', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Выход', exact: true })).toBeVisible();
  await page.screenshot({ path: 'test-results/creator-catalog.png' });
  await page.getByRole('button', { name: 'Добавление', exact: true }).click();
  await page.getByLabel('Название издержки', { exact: true }).fill(name);
  await page.getByLabel('Изображение', { exact: true }).setInputFiles(resolve('public/media/default_cost.png'));
  await page.getByLabel('Видео', { exact: true }).setInputFiles(resolve('public/media/default_cost.mp4'));
  await page.getByRole('button', { name: 'Далее', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Публикация издержки' })).toBeVisible();
  await page.screenshot({ path: 'test-results/creator-draft.png' });
  await page.getByRole('button', { name: 'Плитка', exact: true }).click();
  await page.getByRole('button', { name: 'Добавление', exact: true }).click();
  await expect(page.getByRole('heading', { name: name, exact: true })).toBeVisible();
  await page.getByLabel('Описание издержки', { exact: true }).fill('Проверка полного сценария ЛР6');
  await page.getByLabel('Код издержки', { exact: true }).fill('31');
  await page.getByRole('button', { name: 'Опубликовать', exact: true }).click();
  await page.getByRole('link', { name: new RegExp(name) }).click();
  const id = Number(page.url().split('/').pop());
  await page.getByRole('button', { name: 'Поставить лайк', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Убрать лайк' })).toHaveAttribute('aria-pressed', 'true');
  await page.getByRole('button', { name: 'Убрать лайк' }).click();
  await page.reload();
  await expect(page.getByRole('button', { name: 'Вход', exact: true })).toBeVisible();
  expect((await page.context().cookies()).some(cookie => cookie.name === 'cost_session' && cookie.httpOnly)).toBe(true);
  await expect(page.getByRole('button', { name: 'Поставить лайк' })).toBeDisabled();
  await page.getByRole('button', { name: 'Вход', exact: true }).click();
  await page.getByLabel('Имя пользователя', { exact: true }).fill(name);
  await page.getByLabel('Пароль', { exact: true }).fill(password);
  await page.getByRole('button', { name: 'Войти', exact: true }).click();
  await page.getByLabel('Код издержки от').fill('31');
  await page.getByLabel('Код издержки до').fill('31');
  await page.getByRole('button', { name: 'Применить', exact: true }).click();
  const ownCard = page.locator('.cost-grid > div').filter({ has: page.getByRole('link', { name: new RegExp(name) }) });
  await ownCard.getByRole('button', { name: 'Удалить' }).click();
  await expect(page.getByRole('link', { name: new RegExp(name) })).toHaveCount(0);
  const deleted = await page.request.get(`/api/costs/feed?cost_id=${id}`);
  expect(deleted.status()).toBe(404);
  await page.getByRole('button', { name: 'Выход', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Вход', exact: true })).toBeVisible();
  await expect(page.getByLabel('Код издержки от')).toHaveValue('');
  expect((await page.context().cookies()).some(cookie => cookie.name === 'cost_session')).toBe(false);
});
